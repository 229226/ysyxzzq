#include <ysyxsoc.h>

#define SPI_MASTER_TX0_ADDR     SPI_MASTER_ADDR_BASE+0x00
#define SPI_MASTER_RX0_ADDR     SPI_MASTER_ADDR_BASE+0x00
#define SPI_MASTER_TX1_ADDR     SPI_MASTER_ADDR_BASE+0x04
#define SPI_MASTER_RX1_ADDR     SPI_MASTER_ADDR_BASE+0x04
#define SPI_MASTER_CTRL_ADDR    SPI_MASTER_ADDR_BASE+0x10
#define SPI_MASTER_DIV_ADDR     SPI_MASTER_ADDR_BASE+0x14
#define SPI_MASTER_SS_ADDR      SPI_MASTER_ADDR_BASE+0x18

#define SPI_MASTER_CHAR_LEN_MASK    0x0000007f
#define SPI_MASTER_GO_BSY_MASK      0x00000100
#define SPI_MASTER_RX_NEG_MASK      0x00000200
#define SPI_MASTER_TX_NEG_MASK      0x00000400
#define SPI_MASTER_LSB_MASK         0x00000800
#define SPI_MASTER_IE_MASK          0x00001000
#define SPI_MASTER_ASS_MASK         0x00002000

void __spi_flash_init(){
    outw(SPI_MASTER_DIV_ADDR,0x0000);
    write_rw32(SPI_MASTER_CTRL_ADDR,64,SPI_MASTER_CHAR_LEN_MASK);
    write_rw32(SPI_MASTER_CTRL_ADDR,1,SPI_MASTER_TX_NEG_MASK);
    write_rw32(SPI_MASTER_CTRL_ADDR,0,SPI_MASTER_RX_NEG_MASK);
    write_rw32(SPI_MASTER_CTRL_ADDR,0,SPI_MASTER_LSB_MASK);
    write_rw32(SPI_MASTER_CTRL_ADDR,0,SPI_MASTER_IE_MASK);
    write_rw32(SPI_MASTER_CTRL_ADDR,1,SPI_MASTER_ASS_MASK);
}

uint32_t flash_read(uint32_t addr){
    outb(SPI_MASTER_SS_ADDR,0x01);
    outl(SPI_MASTER_TX1_ADDR,(0x03000000 | (addr&0x00ffffff)));
    outl(SPI_MASTER_TX0_ADDR,0x00000000);
    write_rw32(SPI_MASTER_CTRL_ADDR,1,SPI_MASTER_GO_BSY_MASK);
    while(read_rw32(SPI_MASTER_CTRL_ADDR,SPI_MASTER_GO_BSY_MASK) == 1);
    uint32_t rdata = inl(SPI_MASTER_RX0_ADDR);
    return ((rdata & 0xFF000000) >> 24) |
           ((rdata & 0x00FF0000) >> 8)  |
           ((rdata & 0x0000FF00) << 8)  |
           ((rdata & 0x000000FF) << 24);
}